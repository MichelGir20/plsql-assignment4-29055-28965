SET SERVEROUTPUT ON SIZE UNLIMITED

-- ---------------------------------------------------------------------
-- 0. Clean-up so the script can be re-run. 
-- This is an anonymous PL/SQL block designed to safely drop (delete) all existing tables and custom types before recreating them. 
-- This allows us to run the script over and over without getting "Table already exists" errors.
-- ---------------------------------------------------------------------
BEGIN
  FOR r IN (SELECT column_value AS obj_name
              FROM TABLE(sys.odcivarchar2list(
                     'BULK_ERROR_LOG', 'GRADE_AUDIT', 'ENROLLMENTS',
                     'COURSES', 'STUDENTS', 'DEPARTMENTS', 'PERF_TEST'))) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || r.obj_name || ' CASCADE CONSTRAINTS PURGE';
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE != -942 THEN   -- ORA-00942: table does not exist
          RAISE;
        END IF;
    END;
  END LOOP;

  FOR r IN (SELECT column_value AS type_name
              FROM TABLE(sys.odcivarchar2list(
                     'T_TOP_STUDENT_TAB', 'T_TOP_STUDENT_OBJ', 'T_NUMBER_LIST'))) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TYPE ' || r.type_name || ' FORCE';
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE != -4043 THEN  -- ORA-04043: object does not exist
          RAISE;
        END IF;
    END;
  END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- 1. Tables
-- ---------------------------------------------------------------------
CREATE TABLE departments (
  dept_id    NUMBER(4)    CONSTRAINT pk_departments PRIMARY KEY,
  dept_name  VARCHAR2(60) NOT NULL
                          CONSTRAINT uq_departments_name UNIQUE
);

CREATE TABLE students (
  student_id   NUMBER(6)     CONSTRAINT pk_students PRIMARY KEY,
  first_name   VARCHAR2(40)  NOT NULL,
  last_name    VARCHAR2(40)  NOT NULL,
  email        VARCHAR2(100) NOT NULL
                             CONSTRAINT uq_students_email UNIQUE,
  dept_id      NUMBER(4)     NOT NULL
                             CONSTRAINT fk_students_dept REFERENCES departments (dept_id),
  enroll_date  DATE          DEFAULT SYSDATE NOT NULL,
  status       VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL
                             CONSTRAINT ck_students_status
                             CHECK (status IN ('ACTIVE', 'SUSPENDED', 'GRADUATED'))
);

CREATE TABLE courses (
  course_id     NUMBER(5)     CONSTRAINT pk_courses PRIMARY KEY,
  course_code   VARCHAR2(10)  NOT NULL
                              CONSTRAINT uq_courses_code UNIQUE,
  course_title  VARCHAR2(100) NOT NULL,
  credits       NUMBER(1)     NOT NULL
                              CONSTRAINT ck_courses_credits CHECK (credits BETWEEN 1 AND 6),
  dept_id       NUMBER(4)     NOT NULL
                              CONSTRAINT fk_courses_dept REFERENCES departments (dept_id),
  max_capacity  NUMBER(3)     DEFAULT 30 NOT NULL
                              CONSTRAINT ck_courses_capacity CHECK (max_capacity > 0)
);

CREATE TABLE enrollments (
  enrollment_id  NUMBER GENERATED BY DEFAULT AS IDENTITY
                 CONSTRAINT pk_enrollments PRIMARY KEY,
  student_id     NUMBER(6)    NOT NULL
                 CONSTRAINT fk_enr_student REFERENCES students (student_id),
  course_id      NUMBER(5)    NOT NULL
                 CONSTRAINT fk_enr_course REFERENCES courses (course_id),
  semester       VARCHAR2(12) NOT NULL,
  score          NUMBER(5,2)
                 CONSTRAINT ck_enr_score CHECK (score BETWEEN 0 AND 100),
  grade_letter   CHAR(1)
                 CONSTRAINT ck_enr_grade CHECK (grade_letter IN ('A','B','C','D','F')),
  enroll_date    DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT uq_enr_student_course_sem UNIQUE (student_id, course_id, semester)
);

-- Audit trail of every grade change.
-- enrollment_id is intentionally NOT a foreign key: audit rows must survive
-- even if the enrollment row is later removed.
CREATE TABLE grade_audit (
  audit_id       NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT pk_grade_audit PRIMARY KEY,
  enrollment_id  NUMBER      NOT NULL,
  old_score      NUMBER(5,2),
  new_score      NUMBER(5,2),
  changed_on     TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
  changed_by     VARCHAR2(30) DEFAULT USER NOT NULL
);

-- Rows rejected by FORALL ... SAVE EXCEPTIONS are recorded here.
CREATE TABLE bulk_error_log (
  log_id         NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT pk_bulk_error_log PRIMARY KEY,
  source_proc    VARCHAR2(50)   NOT NULL,
  item_index     NUMBER,
  item_key       VARCHAR2(100),
  error_code     NUMBER,
  error_message  VARCHAR2(4000),
  logged_on      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- Scratch table used only by benchmark_bulk_vs_row.
CREATE TABLE perf_test (
  id   NUMBER CONSTRAINT pk_perf_test PRIMARY KEY,
  val  NUMBER NOT NULL
);

CREATE INDEX ix_enr_course_sem ON enrollments (course_id, semester);

-- ---------------------------------------------------------------------
-- 2. Schema-level collection types
--    (needed so collections can be passed as parameters, returned from
--     functions and queried with TABLE())
-- ---------------------------------------------------------------------
CREATE OR REPLACE TYPE t_number_list AS TABLE OF NUMBER;
/

CREATE OR REPLACE TYPE t_top_student_obj AS OBJECT (
  student_id  NUMBER(6),
  full_name   VARCHAR2(81),
  score       NUMBER(5,2)
);
/

CREATE OR REPLACE TYPE t_top_student_tab AS TABLE OF t_top_student_obj;
/

-- ---------------------------------------------------------------------
